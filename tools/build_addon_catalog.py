"""Generate the offline in-game catalog from the same pinned data as the dashboard."""
import gzip
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def lua(value):
    if isinstance(value, str):
        return re.sub(r"\\u00([0-9a-f]{2})", lambda m: "\\" + f"{int(m[1], 16):03d}",
                      json.dumps(value, ensure_ascii=False))
    if isinstance(value, list):
        return "{" + ",".join(map(lua, value)) + "}"
    if isinstance(value, dict):
        return "{" + ",".join(
            (f"[{key}]" if str(key).isdigit() else key) + "=" + lua(entry)
            for key, entry in value.items() if entry is not None
        ) + "}"
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def generate():
    with gzip.open(ROOT / "src/data/forever.json.gz", "rt") as file:
        data = json.load(file)
    src = data["snapshot"]
    excluded = set(src["non_disenchantable"])
    lines = ["-- Generated by tools/build_addon_catalog.py. Sources and licenses in src/data/.",
             "local _, W = ...", "local items = {}"]
    drops = []
    for key, item in src["items"].items():
        eligible = (int(key) not in excluded and not item.get("no_disenchant")
                    and item.get("class") in (2, 4) and 2 <= item.get("quality", 0) <= 4
                    and item.get("inventory_slot", 0) in set(range(1, 29)) - {4, 19})
        bands = [b["mats"] for b in src["disenchant"] if eligible
                 and b["class"] == item["class"] and b["quality"] == item["quality"]
                 and b["min_level"] <= item.get("level", 0) <= b["max_level"]]
        band = None
        if bands and all(b == bands[0] for b in bands):
            mats = data["overrides"].get(key, bands[0])
            if mats not in drops:
                drops.append(mats)
            band = drops.index(mats) + 1
        binding = item.get("binding")
        entry = dict(name=item["name"], buy=item.get("vendor_buy"), sell=item.get("vendor_sell"),
                     trade=True if binding in ("Unbound","Binds when equipped","Binds when used") else None,
                     bound=True if binding in ("Binds when picked up","Quest item") else None, band=band)
        lines.append(f"items[{key}]={lua(entry)}")
    lines += ["local recipes = {"]
    for r in src["recipes"]:
        req = src["recipe_requirements"][r["id"]]
        lines += [lua(dict(id=r["id"], name=r["name"], output=r["output"], quantity=r["quantity"],
                           mats=r["mats"], profession=req.get("profession"), faction=req.get("faction"),
                           skill=req.get("skill"), cast=req.get("cast_seconds"), cooldown=req.get("cooldown_seconds"))) + ","]
    lines += ["}", "W.catalog={deSeconds=" + lua(data["disenchant_seconds"]) + ",items=items,recipes=recipes,bands=" + lua(drops) + "}"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "addon/WowAuctionSync/Catalog.lua").write_text(generate(), encoding="utf-8")
